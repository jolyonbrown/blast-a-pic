// Searches tray layouts for each level and keeps the one closest to a target
// difficulty. Writes js/tuning.js.
// Usage: node tools/tune-levels.mjs [levelId...]   (CANDIDATES=80 to search fewer)
// Several can run at once on different levels; each merges its results in at the end.
import { writeFileSync, existsSync } from 'node:fs';
import { RAW_LEVELS } from '../js/levels.js';
import { buildLevel } from '../js/engine.js';
import { winRate } from './sim.mjs';

// Target chance of winning by tapping at random, per level (1-based).
const TARGET = [92, 82, 72, 62, 55, 48, 42, 36, 30, 26, 22, 18, 16, 15, 14, 13, 12, 11, 10, 9, 8, 7, 6, 5];
// From level 13 on, the "tap whatever colour is showing most" player should lose
// more and more often too, so levels need genuine planning.
const greedyCeiling = (idx) => (idx < 12 ? 100 : 60 - (idx - 12) * 3);
// ...but a careful one-move-ahead player must still win reasonably often, so the
// difficulty comes from planning, not from needing a single counter-intuitive trick.
const smartFloor = (idx) => (idx < 12 ? 0 : 60 - (idx - 12) * 2.5);

// Expert levels (25+) are steered by the careful player directly: its win rate
// falls steadily level by level. The secret level is the hardest of all.
function expertGoal(def, idx) {
  if (def.secret) return { random: 0, greedyMax: 2, smart: 8, smartMin: 3 };
  // Elite (36+): each new idea arrives a little gentler, then the screw tightens.
  if (def.id >= 36) return { random: 2, greedyMax: 20, smart: 38 - (def.id - 36) * 2.5, smartMin: 15 };
  const i = idx - 24;
  return { random: Math.max(1, 4 - i * 0.4), greedyMax: 25 - i * 1.5, smart: 45 - i * 3, smartMin: 12 };
}

function score(def, idx, r) {
  if (idx < 24) {
    return Math.abs(r.random - (TARGET[idx] ?? 20)) + (idx >= 6 && r.greedy > 90 ? 8 : 0) + (idx < 12 && r.greedy < 30 ? 15 : 0)
      + Math.max(0, r.greedy - greedyCeiling(idx)) * 0.5 + Math.max(0, smartFloor(idx) - r.smart) * 0.8;
  }
  const g = expertGoal(def, idx);
  return Math.abs(r.random - g.random) + Math.max(0, r.greedy - g.greedyMax) * 0.5
    + Math.abs(r.smart - g.smart) * 0.7 + Math.max(0, g.smartMin - r.smart) * 3;
}

const CANDIDATES = +(process.env.CANDIDATES || 150);
const url = new URL('../js/tuning.js', import.meta.url);
const only = process.argv.slice(2).map(Number);
const results = {};

RAW_LEVELS.forEach((def, idx) => {
  if (only.length && !only.includes(def.id)) return;
  let best = null;
  for (let n = 0; n < CANDIDATES; n++) {
    const docks = (def.dockOptions ?? [def.docks ?? 5])[n % (def.dockOptions?.length ?? 1)];
    const noise = (def.noise ?? 1) * (0.5 + (n % 6) * 0.3);
    const seed = def.id * 1000 + n;
    let level;
    try { level = buildLevel({ ...def, docks, noise, seed }); } catch { continue; }
    const r = {
      random: winRate(level, 'random', 120),
      greedy: winRate(level, 'greedy', 60),
      smart: idx >= 12 ? winRate(level, 'smart', idx >= 24 ? 60 : 40) : 100,
    };
    const sc = score(def, idx, r);
    if (!best || sc < best.score) best = { score: sc, ...r, cfg: { seed, docks, noise: +noise.toFixed(2), attempt: level.attempt }, tiles: level.tiles.length };
  }
  if (!best) { console.log(`#${def.id} no candidate`); return; }
  // Store the exact seed that produced the solvable layout so the game rebuilds it first try.
  results[def.id] = best.cfg;
  console.log(`#${String(def.id).padStart(2)} ${def.name.padEnd(18)} random=${best.random}% greedy=${best.greedy}% smart=${best.smart}% docks=${best.cfg.docks} turrets=${best.tiles}`);
});

// Re-read the file just before writing so parallel runs don't overwrite each other.
let tuning = {};
if (existsSync(url)) tuning = (await import(`${url}?t=${Date.now()}`)).TUNING;
Object.assign(tuning, results);
const body = Object.keys(tuning).map(Number).sort((a, b) => a - b).map((id) => `  ${id}: ${JSON.stringify(tuning[id])},`).join('\n');
writeFileSync(url, `// Generated by tools/tune-levels.mjs: which tray layout each level uses.\nexport const TUNING = {\n${body}\n};\n`);
